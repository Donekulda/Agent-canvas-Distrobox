#!/usr/bin/env bash
# Remove Agent Canvas installed directly on the host, so only the box instance exists.
#   scripts/host-cleanup.sh          show findings, confirm, then remove them
#   scripts/host-cleanup.sh --check  only report (exit 1 if anything was found)
#   scripts/host-cleanup.sh --yes    no prompt (used by install.sh --remove-host-install)
# Removes: running host instances, npm/nvm global installs and npx cache entries of
# @openhands/agent-canvas, host state (~/.openhands/agent-canvas, ~/.openhands/automation –
# contains the host install's keys) and the menu entry distrobox generated for the box.
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

check=0 yes=0
case "${1:-}" in
  --check) check=1 ;;
  --yes) yes=1 ;;
  "") ;;
  *) die "usage: $0 [--check | --yes]" ;;
esac

load_env
mapfile -t pids < <(host_running_pids)
mapfile -t installs < <(host_installs)
mapfile -t states < <(host_state_dirs)
entry=()
[[ -f $BOX_ENTRY_FILE ]] && entry=("$BOX_ENTRY_FILE")

if (( ${#pids[@]} + ${#installs[@]} + ${#states[@]} + ${#entry[@]} == 0 )); then
  ok "no Agent Canvas on the host outside the box"
  exit 0
fi

log "Found on the host (outside the box):"
for p in "${pids[@]}"; do printf '   running:     pid %s  %s\n' "$p" "$(ps -o args= -p "$p" | cut -c1-80)"; done
for p in "${installs[@]}"; do printf '   install:     %s\n' "$p"; done
for p in "${states[@]}"; do printf '   state/keys:  %s\n' "$p"; done
for p in "${entry[@]}"; do printf '   menu entry:  %s (generated by distrobox)\n' "$p"; done
(( ! check )) || exit 1

if (( ! yes )); then
  confirm "Stop and permanently delete all of the above? (the box and its data are not touched)" || die "aborted"
fi

if (( ${#pids[@]} )); then
  kill -TERM "${pids[@]}" 2>/dev/null || true
  for _ in $(seq 10); do
    [[ -z $(host_running_pids) ]] && break
    sleep 1
  done
  mapfile -t pids < <(host_running_pids)
  (( ${#pids[@]} == 0 )) || kill -KILL "${pids[@]}" 2>/dev/null || true
  ok "host instances stopped"
fi

for mod in "${installs[@]}"; do
  case "$mod" in
    "$HOME"/.npm/_npx/*)
      # npx cache entry: ~/.npm/_npx/<hash>/node_modules/@openhands/agent-canvas
      rm -rf -- "${mod%/node_modules/@openhands/agent-canvas}"
      ok "removed npx cache entry ${mod%/node_modules/@openhands/agent-canvas}"
      ;;
    /usr/*)
      warn "system-wide install $mod – remove it yourself: sudo npm rm -g @openhands/agent-canvas"
      ;;
    *)
      prefix="${mod%/lib/node_modules/@openhands/agent-canvas}"
      if [[ -x $prefix/bin/npm ]]; then
        # Use the npm of that node version (nvm), with its node first on PATH.
        PATH="$prefix/bin:$PATH" "$prefix/bin/npm" rm -g @openhands/agent-canvas >/dev/null
      else
        rm -rf -- "$mod"
        [[ -L $prefix/bin/agent-canvas ]] && rm -f -- "$prefix/bin/agent-canvas"
      fi
      rmdir "${mod%/agent-canvas}" 2>/dev/null || true # empty @openhands scope dir
      ok "uninstalled $mod"
      ;;
  esac
done

for d in "${states[@]}"; do
  rm -rf -- "$d"
  ok "deleted $d"
done
rmdir "$HOME/.openhands" 2>/dev/null || true

if (( ${#entry[@]} )); then
  distrobox generate-entry "$BOX_NAME" --delete >/dev/null 2>&1 || rm -f -- "$BOX_ENTRY_FILE"
  ok "removed distrobox menu entry"
fi

hash -r
ok "host cleanup done – Agent Canvas now runs only from the box"
